#include <stdio.h>

int main()
{
    int age = 18;
    float marks = 85.5;
    char grade = 'A';
    double pi = 3.141592;

    printf("Integer = %d\n", age);
    printf("Float = %.2f\n", marks);
    printf("Character = %c\n", grade);
    printf("Double = %lf\n", pi);

    return 0;
}